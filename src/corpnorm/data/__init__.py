def prefecture_from_postal(code7: str) -> str | None:
    """7 桁郵便番号の上位 3 桁から都道府県を推定する。"""
    if len(code7) < 3 or not code7[:3].isdigit():
        return None
    head = int(code7[:3])
    for lo, hi, pref in POSTAL_PREFIX_RANGES:
        if lo <= head <= hi:
            return pref
    return None


